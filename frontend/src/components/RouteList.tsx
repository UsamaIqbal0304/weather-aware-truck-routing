import type { Route, RouteSummary } from "../api/types";
import { clockWithDay, duration, miles } from "../lib/format";
import { RISK_BANDS, RISK_COLORS, riskLabel } from "../lib/risk";

interface Props {
  routes: Route[];
  selectedRouteId: string | null;
  onSelect: (routeId: string) => void;
}

function bandMiles(summary: RouteSummary, level: number): number {
  switch (level) {
    case 1:
      return summary.low_miles;
    case 2:
      return summary.moderate_miles;
    case 3:
      return summary.high_miles;
    case 4:
      return summary.severe_miles;
    case 5:
      return summary.no_travel_miles;
    default:
      return 0;
  }
}

/**
 * How the route's miles divide across the five bands, as one bar.
 *
 * A bar rather than five numbers because the comparison a dispatcher
 * actually makes is "how much of this trip is red", and a proportion is
 * read faster from length than from digits. The numbers are still in the
 * table below for anyone who needs them.
 */
function RiskBar({ summary }: { summary: RouteSummary }) {
  const total = summary.assessed_miles + summary.unassessed_miles || 1;
  return (
    <div className="riskbar" role="img" aria-label={riskBarLabel(summary)}>
      {RISK_BANDS.map((level) => {
        const value = bandMiles(summary, level);
        if (value <= 0) return null;
        return (
          <span
            key={level}
            className="riskbar__segment"
            style={{ width: `${(value / total) * 100}%`, background: RISK_COLORS[level] }}
          />
        );
      })}
      {summary.unassessed_miles > 0 && (
        <span
          className="riskbar__segment riskbar__segment--unknown"
          style={{ width: `${(summary.unassessed_miles / total) * 100}%` }}
        />
      )}
    </div>
  );
}

function riskBarLabel(summary: RouteSummary): string {
  const parts = RISK_BANDS.filter((level) => bandMiles(summary, level) > 0).map(
    (level) => `${miles(bandMiles(summary, level))} ${riskLabel(level)}`,
  );
  return parts.join(", ") || "no assessed miles";
}

export function RouteList({ routes, selectedRouteId, onSelect }: Props) {
  return (
    <ul className="routes">
      {routes.map((route) => {
        const summary = route.summary;
        const selected = route.id === selectedRouteId;
        return (
          <li key={route.id}>
            <button
              type="button"
              className={`route${selected ? " is-selected" : ""}${
                route.recommended ? " is-recommended" : ""
              }`}
              onClick={() => onSelect(route.id)}
              aria-pressed={selected}
            >
              <div className="route__head">
                <span className="route__name">{route.name}</span>
                {route.recommended && <span className="badge badge--good">Recommended</span>}
                {route.blocked && <span className="badge badge--block">No Travel</span>}
                {route.source.includes("detour") && (
                  <span
                    className="badge badge--muted"
                    title="The routing engine offered fewer than three alternatives, so this one was generated by routing through an offset waypoint."
                  >
                    Synthesised
                  </span>
                )}
              </div>

              <div className="route__stats">
                <span>{miles(route.distance_miles)}</span>
                <span>{duration(route.duration_hours)}</span>
                <span title="Estimated arrival">arrive {clockWithDay(route.arrival)}</span>
              </div>

              {summary && (
                <>
                  <RiskBar summary={summary} />
                  <dl className="route__metrics">
                    <div>
                      <dt>Severe</dt>
                      <dd className={summary.severe_miles > 0 ? "is-bad" : ""}>
                        {miles(summary.severe_miles)}
                      </dd>
                    </div>
                    <div>
                      <dt>High</dt>
                      <dd className={summary.high_miles > 0 ? "is-warn" : ""}>
                        {miles(summary.high_miles)}
                      </dd>
                    </div>
                    <div>
                      <dt>Avg risk</dt>
                      <dd>{summary.average_risk.toFixed(2)}</dd>
                    </div>
                    <div>
                      <dt>Worst</dt>
                      <dd>{summary.max_risk_label}</dd>
                    </div>
                  </dl>
                  {summary.unassessed_miles > 0 && (
                    <p className="route__note">
                      {miles(summary.unassessed_miles)} beyond the forecast horizon and not scored.
                    </p>
                  )}
                </>
              )}
            </button>
          </li>
        );
      })}
    </ul>
  );
}
